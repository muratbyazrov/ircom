export const normalizePhotoReference = (value) => {
  const raw = String(value || "").trim();
  if (!raw) return "";
  if (/^https?:\/\//i.test(raw)) return raw;
  if (!PHOTO_PUBLIC_BASE_URL) return raw;
  return `${PHOTO_PUBLIC_BASE_URL}/${encodeURIComponent(raw).replace(/%2F/g, "/")}`;
};
